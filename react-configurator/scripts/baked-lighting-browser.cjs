// Visual smoke evidence, not an approved screenshot regression baseline.
const {chromium}=require('playwright')
const {mkdirSync,writeFileSync}=require('node:fs')
const assert=require('node:assert/strict')
const path=require('node:path')

async function main(){
  const output=path.resolve('test-results/baked-lighting')
  mkdirSync(output,{recursive:true})
  const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome',headless:true})
  const failures=[],results=[]
  try{
    for(const mobile of [false,true]){
      const context=await browser.newContext({viewport:mobile?{width:390,height:844}:{width:1440,height:1100},isMobile:mobile,hasTouch:mobile})
      const page=await context.newPage()
      await page.route('**/favicon.ico',route=>route.fulfill({status:204,body:''}))
      page.on('pageerror',error=>{failures.push(error.message);console.error(error.message)})
      page.on('console',message=>{if(message.type()==='error')failures.push(message.text())})
      const label=mobile?'mobile':'desktop'
      console.log('CHECKING',label)
      const ready=async()=>{
        await page.locator('canvas[data-scene-ready="true"]').waitFor({timeout:60000})
        await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
      }
      await page.goto(process.env.KITCHEN_APP_URL||'http://127.0.0.1:5173',{waitUntil:'domcontentloaded'})
      await page.getByRole('button',{name:'Open Bedroom 3',exact:true}).first().click()
      await ready()
      await page.screenshot({path:path.join(output,`${label}-bedroom-overview.png`),fullPage:true})
      await page.getByRole('button',{name:'Eye-level view',exact:true}).click()
      const canvas=page.locator('canvas[data-scene-ready="true"]')
      await canvas.scrollIntoViewIfNeeded()
      await page.waitForTimeout(700)
      const before=await canvas.screenshot({path:path.join(output,`${label}-bedroom-eye.png`)})
      const existingCanvas=await canvas.elementHandle()
      let modelReloads=0
      const countModel=request=>{if(request.url().includes('.glb'))modelReloads++}
      page.on('request',countModel)
      const brightness=page.getByRole('slider',{name:'Model brightness'})
      assert.equal(await brightness.inputValue(),'1.5')
      await brightness.fill('2')
      await page.waitForTimeout(300)
      const brighter=await canvas.screenshot({path:path.join(output,`${label}-bedroom-brighter.png`)})
      assert.ok(!before.equals(brighter),'brightness changes the rendered image')
      assert.ok(await existingCanvas.evaluate(element=>element.isConnected),'brightness retains the existing canvas')
      assert.equal(modelReloads,0,'brightness does not reload the model')
      await brightness.fill('1.5')
      await existingCanvas.dispose()
      page.off('request',countModel)
      const box=await canvas.boundingBox()
      await page.mouse.move(box.x+box.width*.5,box.y+box.height*.4)
      await page.mouse.down()
      await page.mouse.move(box.x+box.width*.67,box.y+box.height*.44,{steps:12})
      await page.mouse.up()
      await page.mouse.wheel(0,-140)
      await page.waitForTimeout(700)
      const after=await canvas.screenshot({path:path.join(output,`${label}-bedroom-orbit.png`)})
      assert.ok(!before.equals(after),'orbit/zoom changes rendered view')
      await page.getByLabel('Model lighting').selectOption('studio')
      await ready()
      await page.getByLabel('Model lighting').selectOption('baked')
      await ready()
      await page.getByRole('button',{name:'Blender render',exact:true}).click()
      await page.getByAltText('Bedroom 3 Blender lighting and finish render').waitFor()
      await page.getByRole('button',{name:'Editable workspace',exact:true}).click()
      assert.equal(await page.getByRole('button',{name:'Editable workspace',exact:true}).getAttribute('aria-pressed'),'true')
      await page.getByRole('button',{name:'Blender model',exact:true}).click()
      await ready()
      for(const room of ['Drawing Room','Pooja']){
        await page.getByRole('button',{name:'Return to whole home plan',exact:true}).click()
        await page.getByRole('button',{name:room==='Pooja'?'Open Pooja Ghar':`Open ${room}`,exact:true}).first().click()
        await ready()
        await page.screenshot({path:path.join(output,`${label}-${room.replaceAll(' ','-')}.png`),fullPage:true})
        if(room==='Drawing Room'){
          await page.getByRole('button',{name:'Eye-level view',exact:true}).click()
          await page.waitForTimeout(700)
          const drawingCanvas=page.locator('canvas[data-scene-ready="true"]')
          const drawingBefore=await drawingCanvas.screenshot({path:path.join(output,`${label}-drawing-eye.png`)})
          const drawingBox=await drawingCanvas.boundingBox()
          await page.mouse.move(drawingBox.x+drawingBox.width*.5,drawingBox.y+drawingBox.height*.4)
          await page.mouse.down()
          await page.mouse.move(drawingBox.x+drawingBox.width*.56,drawingBox.y+drawingBox.height*.42,{steps:8})
          await page.mouse.up()
          await page.mouse.wheel(0,-60)
          await page.waitForTimeout(500)
          const drawingAfter=await drawingCanvas.screenshot({path:path.join(output,`${label}-drawing-orbit.png`)})
          assert.ok(!drawingBefore.equals(drawingAfter),'drawing room supports orbit and zoom')
          await page.getByRole('button',{name:'Blender render',exact:true}).click()
          await page.getByAltText('Drawing Room Blender lighting and finish render').waitFor()
          await page.screenshot({path:path.join(output,`${label}-drawing-render.png`),fullPage:true})
        }
      }
      await page.getByRole('button',{name:'Whole home 3D',exact:true}).first().click()
      // Whole home 3D opens on Editable 3D since 2026-10-03; the baked model is one click away.
      await page.getByRole('button',{name:'Blender model',exact:true}).click()
      await ready()
      await page.screenshot({path:path.join(output,`${label}-whole-home.png`),fullPage:true})
      await page.getByRole('button',{name:'Blender renders and tour',exact:true}).click()
      await page.getByRole('heading',{name:'Lighting and finish previews'}).waitFor()
      await page.getByRole('button',{name:'Editable 3D',exact:true}).click()
      assert.equal(await page.getByRole('button',{name:'Editable 3D',exact:true}).getAttribute('aria-pressed'),'true')
      await page.getByRole('button',{name:'Blender model',exact:true}).click()
      await ready()
      results.push({viewport:label,orbitAndZoom:true,brightnessWithoutReload:true,lightingSwitch:true,roomAndWholeHomeTabs:true})
      await context.close()
    }
    assert.deepEqual(failures,[],'no browser errors')
    writeFileSync(path.join(output,'results.json'),JSON.stringify({results,failures},null,2))
    console.log(JSON.stringify({results,failures},null,2))
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
