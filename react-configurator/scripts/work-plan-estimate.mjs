// Recomputes the budget fields of work-plan/plan.json from the app's configs and the rate table, and rewrites the two
// generated documents: docs/WORK_PLAN_BUDGET.md (rates, totals, what moves the total, what is not estimated) and
// docs/NEXT_STEPS.md (what to measure and decide first). Run from react-configurator/:
//   node scripts/work-plan-estimate.mjs           write the files
//   node scripts/work-plan-estimate.mjs --check   write nothing; exit 1 if anything would change
// The plan is written exactly as the Work plan page's save endpoint writes it (JSON, two-space indent, one final newline),
// keeping the line endings the file already has.
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {validateWorkPlan, checkDependencies, budgetTotals, openItemImpact, readyTaskImpact, formatInr} from '../src/home/workPlan.mjs'
import {RATES, applyEstimates, rateContributions} from '../src/home/workPlanEstimate.mjs'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const PLAN = path.join(repo, 'work-plan/plan.json'), OPEN = path.join(repo, 'work-plan/OPEN_ITEMS.md')
const BUDGET_DOC = path.join(repo, 'docs/WORK_PLAN_BUDGET.md'), NEXT_DOC = path.join(repo, 'docs/NEXT_STEPS.md')

/** Open items from OPEN_ITEMS.md: id -> {text, closed}. A row is closed when its text starts with ANSWERED, CLOSED or DONE. */
export function readOpenItems(markdown) {
  const items = new Map()
  for (const line of markdown.split(/\r?\n/)) {
    const match = /^\|\s*([A-E][0-9]+)\s*\|\s*(.*?)\s*\|/.exec(line)
    if (match) items.set(match[1], {text: match[2], closed: /^(ANSWERED|CLOSED|DONE)\b/.test(match[2])})
  }
  return items
}

const short = (text, max = 150) => { const one = text.replace(/\s+/g, ' '); return one.length <= max ? one : `${one.slice(0, one.lastIndexOf(' ', max))} ...` }
const amount = value => value >= 100 ? Math.round(value).toLocaleString('en-IN') : String(Math.round(value * 10) / 10)

export function budgetDocument(plan) {
  const totals = budgetTotals(plan), all = totals.all
  const contributions = rateContributions(plan.tasks.map(task => task.id))
  const table = (title, rows) => [`### ${title}`, '', `| ${title} | Tasks | Low | High | Not estimated |`, '| --- | ---: | ---: | ---: | ---: |',
    ...rows.map(row => `| ${row.name} | ${row.tasks} | ${row.estimated ? formatInr(row.low) : 'not estimated'} | ${row.estimated ? formatInr(row.high) : 'not estimated'} | ${row.notEstimated || ''} |`), '']
  const optional = plan.tasks.find(task => task.id === 'skirting')
  const lowConfidence = plan.tasks.filter(task => task.estimateConfidence === 'low')
  return [
    '# Work plan budget: planning ranges, not quotes',
    '',
    'GENERATED by `react-configurator/scripts/work-plan-estimate.mjs` from `work-plan/plan.json`, the app\'s configs and the rate',
    'table in `react-configurator/src/home/workPlanEstimate.mjs`. Do not edit by hand: correct a rate or a quantity there and',
    're-run the script (or tell the assistant which rate is wrong).',
    '',
    '## How to read it',
    '',
    '- Every figure is a quantity from the 3D model multiplied by a typical 2025-26 Delhi NCR rate for mid-range quality.',
    '  Labour and material are both in the rate unless the rate says otherwise. Model sizes are not site measurements.',
    '- NOT included: GST (18 % on most contractor bills), a contingency (10-15 % is usual for work in an old flat), kitchen',
    '  appliances, loose furniture, the society\'s fee or deposit, and anything in a task listed under "Not estimated".',
    '- "Low" and "high" are the ends of the usual rate range, not the cheapest and dearest possible. A real quote can fall',
    '  outside the range; replace the range with the quote in the task notes when one arrives.',
    `- Confidence: ${lowConfidence.length} of the ${all.estimated} estimated tasks are marked low (the design is not frozen, or the size is not measured).`,
    '',
    '## Total',
    '',
    `**${formatInr(all.low)} to ${formatInr(all.high)}** (${formatInr(all.low, {short: true})} to ${formatInr(all.high, {short: true})}) for the ${all.estimated} tasks that could be`,
    `estimated, out of ${all.tasks}. ${all.notEstimated} tasks are not estimated (listed below), so the true total is higher.`,
    optional?.estimateLow != null ? `The total includes the OPTIONAL skirting replacement (${formatInr(optional.estimateLow)} to ${formatInr(optional.estimateHigh)}).` : '',
    '',
    ...table('Phase', totals.byPhase), ...table('Trade', totals.byTrade), ...table('Room', totals.byRoom),
    '## The five numbers the total is most sensitive to',
    '',
    'Each row is one rate and all the quantity priced with it. If the rate is 10 % off, the high total moves by a tenth of the',
    '"High" column. These are the first five to check against a real quote.',
    '',
    '| # | Rate | Quantity | Rate (Rs) | Low | High | Share of the high total |',
    '| --- | --- | ---: | --- | ---: | ---: | ---: |',
    ...contributions.slice(0, 5).map((row, index) => `| ${index + 1} | ${RATES[row.rate].label} | ${row.quantityLow === row.quantityHigh ? amount(row.quantityLow) : `${amount(row.quantityLow)} to ${amount(row.quantityHigh)}`} ${RATES[row.rate].unit} | ${amount(RATES[row.rate].low)}-${amount(RATES[row.rate].high)} | ${formatInr(Math.round(row.low))} | ${formatInr(Math.round(row.high))} | ${Math.round(row.high / all.high * 100)} % |`),
    '',
    '## Not estimated, and why',
    '',
    '| Task | Why |',
    '| --- | --- |',
    ...totals.notEstimated.map(row => `| ${row.title} | ${row.reason.replace(/^Not estimated: /, '')} |`),
    '',
    '## Rates used (correct these)',
    '',
    'Rupees, 2025-26, Delhi NCR, mid-range quality. "Used for" is the total quantity across the plan.',
    '',
    '| Rate | Unit | Low | High | Used for |',
    '| --- | --- | ---: | ---: | ---: |',
    ...Object.entries(RATES).map(([id, rate]) => { const used = contributions.find(row => row.rate === id); return `| ${rate.label} | ${rate.unit} | ${amount(rate.low)} | ${amount(rate.high)} | ${used ? (used.quantityLow === used.quantityHigh ? amount(used.quantityLow) : `${amount(used.quantityLow)} to ${amount(used.quantityHigh)}`) : 'not used'} |` }),
    '',
    '## Every task',
    '',
    '| Task | Room | Low | High | Confidence | Basis |',
    '| --- | --- | ---: | ---: | --- | --- |',
    ...plan.tasks.map(task => `| ${task.title} | ${task.room} | ${task.estimateLow == null ? '' : formatInr(task.estimateLow)} | ${task.estimateHigh == null ? '' : formatInr(task.estimateHigh)} | ${task.estimateConfidence ?? ''} | ${task.estimateBasis ?? ''} |`),
    '',
  ].join('\n')
}

export function nextStepsDocument(plan, openItems) {
  const impact = openItemImpact(plan), titles = new Map(plan.tasks.map(task => [task.id, task.title]))
  const kind = {A: 'Measure', B: 'Find out', C: 'Decide', D: 'Arrange', E: 'Confirm'}
  const ready = readyTaskImpact(plan), FIRST = 20
  const head = ['| # | Item | What | Tasks waiting | Directly | Named by |', '| ---: | --- | --- | ---: | ---: | --- |']
  const named = ids => `${ids.slice(0, 2).map(id => short(titles.get(id), 60)).join('; ')}${ids.length > 2 ? `; and ${ids.length - 2} more` : ''}`
  const line = (row, index) => `| ${index + 1} | ${row.item} | ${kind[row.item[0]]}: ${short(openItems.get(row.item)?.text ?? '(not in OPEN_ITEMS.md)')} | ${row.waiting} | ${row.direct.length} | ${named(row.direct)} |`
  return [
    '# What to do first',
    '',
    'GENERATED by `react-configurator/scripts/work-plan-estimate.mjs` from `work-plan/plan.json` and `work-plan/OPEN_ITEMS.md`.',
    'Do not edit by hand; answer an item in OPEN_ITEMS.md (or tell the assistant) and re-run the script.',
    '',
    'The order is computed, not guessed. Each task in the plan names the open items it is waiting for. "Tasks waiting" counts',
    'those tasks plus every task behind them in the order of work. "Directly" counts only the tasks that name the item.',
    `Because plaster, paint and the final snag list sit behind almost everything, many items share a high count; among equals,`,
    'the one named by more tasks comes first.',
    '',
    '## The first twenty: measurements, facts, decisions and people, most-blocking first',
    '',
    ...head, ...impact.slice(0, FIRST).map(line),
    '',
    '## The rest, in the same order',
    '',
    ...head, ...impact.slice(FIRST).map((row, index) => line(row, index + FIRST)),
    '',
    '## Tasks that can start today',
    '',
    'Nothing has to be finished before these. The number is how many tasks cannot finish until this one is done.',
    '',
    '| Task | Tasks behind it |',
    '| --- | ---: |',
    ...ready.map(row => `| ${titles.get(row.task)} | ${row.waiting} |`),
    '',
  ].join('\n')
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const check = process.argv.includes('--check')
  const raw = fs.readFileSync(PLAN, 'utf8'), eol = raw.includes('\r\n') ? '\r\n' : '\n'
  const plan = validateWorkPlan(JSON.parse(raw))
  const missing = applyEstimates(plan)
  validateWorkPlan(plan)
  const problems = checkDependencies(plan)
  if (problems.length) { console.error(problems.map(problem => problem.message).join('\n')); process.exit(1) }
  const openItems = readOpenItems(fs.readFileSync(OPEN, 'utf8'))
  const outputs = [
    [PLAN, `${JSON.stringify(plan, null, 2)}\n`.replace(/\n/g, eol)],
    [BUDGET_DOC, budgetDocument(plan).replace(/\n/g, eol)],
    [NEXT_DOC, nextStepsDocument(plan, openItems).replace(/\n/g, eol)],
  ]
  let changed = 0
  for (const [file, content] of outputs) {
    const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
    if (before === content) continue
    changed++
    if (check) console.error(`Out of date: ${path.relative(repo, file)}`); else { fs.writeFileSync(file, content); console.log(`Wrote ${path.relative(repo, file)}`) }
  }
  const all = budgetTotals(plan).all
  console.log(`${plan.tasks.length} tasks; ${all.estimated} estimated: ${formatInr(all.low)} to ${formatInr(all.high)}; ${all.notEstimated} not estimated.`)
  if (missing.length) console.log(`No estimator for (left as they are): ${missing.join(', ')}`)
  if (check && changed) process.exit(1)
}
